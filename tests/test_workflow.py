"""Tests for GitHub Actions workflow generation."""

import yaml

from pipebridge.analysis import analyze_source
from pipebridge.workflow import generate_workflow

CHECKOUT_SHA = "3d3c42e5aac5ba805825da76410c181273ba90b1"

CLEAN = (
    "pipeline {\n"
    "    agent any\n"
    "    environment {\n"
    "        APP_ENV = 'production'\n"
    "    }\n"
    "    stages {\n"
    "        stage('Build') {\n"
    "            environment {\n"
    "                BUILD_DIR = 'target'\n"
    "            }\n"
    "            steps {\n"
    "                checkout scm\n"
    "                sh 'make build'\n"
    "                echo 'build done'\n"
    "            }\n"
    "        }\n"
    "        stage('Test') {\n"
    "            steps {\n"
    "                sh '''\n"
    "                    export REPORTS_DIR=$PWD/reports\n"
    "                    ./run-tests.sh --dir \"$REPORTS_DIR\"\n"
    "                '''\n"
    "            }\n"
    "        }\n"
    "    }\n"
    "}\n"
)


def gen(source, name="Jenkinsfile"):
    return generate_workflow(analyze_source(source), source_name=name)


def wf(source):
    return yaml.safe_load(gen(source))


def test_header_documents_source_hash_and_version():
    text = gen(CLEAN)
    assert "# Generated by pipebridge" in text
    assert "sha256: " in text
    assert CHECKOUT_SHA[:12] in text or "sha256:" in text


def test_trigger_permissions_and_shell_defaults():
    parsed = wf(CLEAN)
    trigger = parsed.get(True, parsed.get("on"))  # PyYAML 1.1 parses `on:` as True
    assert trigger == {"workflow_dispatch": None}
    assert parsed["permissions"] == {"contents": "read"}
    assert parsed["defaults"]["run"]["shell"] == "bash"


def test_job_runs_on_ubuntu_and_single_job():
    parsed = wf(CLEAN)
    jobs = parsed["jobs"]
    assert list(jobs) == ["migrated-pipeline"]
    job = jobs["migrated-pipeline"]
    assert job["runs-on"] == "ubuntu-latest"
    assert "if" not in job  # no blockers -> not disabled


def test_stages_become_ordered_steps_with_stage_names():
    parsed = wf(CLEAN)
    steps = parsed["jobs"]["migrated-pipeline"]["steps"]
    names = [s["name"] for s in steps]
    assert names[0] == "Build"
    assert names[1] == "Build (step 2)"
    assert names[2] == "Build (step 3)"
    assert names[3] == "Test"
    # All steps in one job, in source order (shared workspace).
    run_texts = [s.get("run", "") for s in steps]
    assert "make build" in run_texts[1]
    assert "./run-tests.sh --dir \"$REPORTS_DIR\"" in run_texts[3]


def test_pipeline_env_at_job_level_and_stage_env_on_steps_only():
    parsed = wf(CLEAN)
    job = parsed["jobs"]["migrated-pipeline"]
    assert job["env"] == {"APP_ENV": "production"}
    steps = job["steps"]
    assert steps[0]["env"] == {"BUILD_DIR": "target"}  # Build stage env on all its steps
    assert steps[1]["env"] == {"BUILD_DIR": "target"}
    assert "env" not in steps[3]  # Test stage has no stage env


def test_checkout_is_pinned_to_full_sha_with_version():
    text = gen(CLEAN)
    assert f"uses: actions/checkout@{CHECKOUT_SHA} #" in text
    assert "v7.0.1" in text


def test_echo_becomes_printf():
    parsed = wf(CLEAN)
    run = parsed["jobs"]["migrated-pipeline"]["steps"][2]["run"]
    assert run == "printf '%s\\n' 'build done'"


def test_shell_variables_preserved_verbatim():
    parsed = wf(CLEAN)
    run = parsed["jobs"]["migrated-pipeline"]["steps"][3]["run"]
    assert "export REPORTS_DIR=$PWD/reports" in run
    assert '"$REPORTS_DIR"' in run


def test_github_expression_in_source_is_neutralized():
    source = CLEAN.replace(
        "sh 'make build'",
        "sh 'deploy-tool --token ${{ secrets.DEPLOY_TOKEN }}'",
    )
    text = gen(source)
    assert "${{ '${{' }}" in text  # neutralized in the YAML source
    parsed = yaml.safe_load(text)
    steps = parsed["jobs"]["migrated-pipeline"]["steps"]
    run = next(s["run"] for s in steps if s["name"] == "Build (step 2)")
    # After GitHub's own substitution, the shell sees the original literal.
    assert run.replace("${{ '${{' }}", "${{") == (
        "deploy-tool --token ${{ secrets.DEPLOY_TOKEN }}"
    )


def test_blockers_disable_job_with_false_condition_and_comment():
    source = (
        "pipeline {\n"
        "    agent any\n"
        "    stages {\n"
        "        stage('Deploy') {\n"
        "            steps {\n"
        "                script {\n"
        "                    sh 'evil'\n"
        "                }\n"
        "            }\n"
        "        }\n"
        "    }\n"
        "}\n"
    )
    text = gen(source)
    parsed = yaml.safe_load(text)
    job = parsed["jobs"]["migrated-pipeline"]
    assert job["if"] is False
    assert "PB-SCRIPT" in text  # comment explains which blockers
    steps = job["steps"]
    assert len(steps) == 1
    assert steps[0]["name"] == "[NOT MIGRATED] Deploy"
    assert "exit 1" in steps[0]["run"]
    assert "evil" not in steps[0]["run"]  # never extracted


def test_pipeline_level_blocker_produces_skeleton_without_steps():
    source = (
        "pipeline {\n"
        "    agent {\n"
        "        docker {\n"
        "            image 'node:20'\n"
        "        }\n"
        "    }\n"
        "    stages {\n"
        "        stage('Build') {\n"
        "            steps {\n"
        "                sh 'make build'\n"
        "            }\n"
        "        }\n"
        "    }\n"
        "}\n"
    )
    text = gen(source)
    parsed = yaml.safe_load(text)
    job = parsed["jobs"]["migrated-pipeline"]
    assert job["if"] is False
    assert "PB-AGENT" in text
    # A job requires a steps section: the only content is a loud placeholder.
    steps = job["steps"]
    assert len(steps) == 1
    assert steps[0]["name"] == "[NOT MIGRATED] pipeline"
    assert "make build" not in steps[0]["run"]  # never extracted
    assert "exit 1" in steps[0]["run"]
    # Stage name still listed (as a comment) for review.
    assert 'stage "Build" (line 8)' in text


def test_yaml_special_env_values_roundtrip_as_strings():
    source = (
        "pipeline {\n"
        "    agent any\n"
        "    environment {\n"
        "        FLAG = 'on'\n"
        "        NUM = '8080'\n"
        "        STAR = '*RESET*'\n"
        "    }\n"
        "    stages {\n"
        "        stage('A') {\n"
        "            steps {\n"
        "                echo 'x'\n"
        "            }\n"
        "        }\n"
        "    }\n"
        "    post {\n"
        "        always {\n"
        "            echo 'bye'\n"
        "        }\n"
        "    }\n"
        "}\n"
    )
    parsed = wf(source)
    env = parsed["jobs"]["migrated-pipeline"]["env"]
    assert env == {"FLAG": "on", "NUM": "8080", "STAR": "*RESET*"}
    assert all(isinstance(v, str) for v in env.values())


def test_stage_name_with_yaml_specials_is_quoted():
    source = (
        "pipeline {\n"
        "    agent any\n"
        "    stages {\n"
        "        stage('Build & \"Test\"') {\n"
        "            steps {\n"
        "                echo 'x'\n"
        "            }\n"
        "        }\n"
        "    }\n"
        "}\n"
    )
    parsed = wf(source)
    steps = parsed["jobs"]["migrated-pipeline"]["steps"]
    assert steps[0]["name"] == 'Build & "Test"'


def test_generation_is_deterministic():
    assert gen(CLEAN) == gen(CLEAN)


def test_multiline_string_with_leading_indentation_roundtrips():
    source = (
        "pipeline {\n"
        "    agent any\n"
        "    stages {\n"
        "        stage('A') {\n"
        "            steps {\n"
        "                sh '''    echo starts-with-spaces\n"
        "                    echo second line\n"
        "                '''\n"
        "            }\n"
        "        }\n"
        "    }\n"
        "}\n"
    )
    text = gen(source)
    parsed = yaml.safe_load(text)
    run = parsed["jobs"]["migrated-pipeline"]["steps"][0]["run"]
    assert run == "    echo starts-with-spaces\n                    echo second line\n                "
