"""GitHub Actions workflow generation.

Generation is deterministic (no timestamps) and never executes anything.
Blockers disable the job with a literal ``if: false`` condition plus an
explanatory comment; blocked stages become placeholder steps that fail
loudly instead of pretending to succeed.
"""

from __future__ import annotations

import json
import re

from . import __version__
from .analysis import AnalysisResult, models_implicit_checkout
from .model import EnvVar, Pipeline, Span, Stage

# actions/checkout pinned to a verified full commit SHA.
# v7.0.1 == 3d3c42e5aac5ba805825da76410c181273ba90b1 (verified via
# `git ls-remote https://github.com/actions/checkout.git refs/tags/v7.0.1`).
# Re-verify and update deliberately when bumping.
CHECKOUT_ACTION_REPO = "actions/checkout"
CHECKOUT_ACTION_SHA = "3d3c42e5aac5ba805825da76410c181273ba90b1"
CHECKOUT_ACTION_VERSION = "v7.0.1"

_GH_EXPR = "${{"
_GH_EXPR_ESCAPED = "${{ '${{' }}"
# Shell concatenation that reconstructs a literal ``${{`` at runtime while
# the raw script contains no ``${{`` sequence for GitHub to evaluate:
# '$' + '{{' -> ${{
_SHELL_EXPR_LITERAL = "'$''{{'"
_PLAIN_OK = frozenset(
    "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-/. "
)
_RESERVED_WORDS = frozenset(
    {"true", "false", "null", "yes", "no", "on", "off", "~", "none"}
)
_NUMERIC_RE = re.compile(r"[-+]?\d[\d_.]*")


def escape_github_expressions(text: str) -> str:
    """Neutralize GitHub expression syntax in literal source text.

    For text placed in fields GitHub itself evaluates (step names, env
    values, unquoted run scripts): each ``${{`` is replaced by an
    expression that evaluates back to the literal ``${{``, so GitHub's
    substitution leaves the original text behind.
    """
    return text.replace(_GH_EXPR, _GH_EXPR_ESCAPED)


def _expr_safe_shell_quote(text: str) -> str:
    """Single-quote source text for shell with no ``${{`` in the result.

    Shell quoting does NOT protect ``${{ ... }}``: GitHub substitutes
    expressions in run scripts before the shell runs, and the documented
    escaping idiom breaks when it lands inside shell quotes. Instead, the
    text is split on ``${{`` and the pieces are single-quoted separately,
    joined by a shell concatenation that rebuilds the literal ``${{`` at
    runtime. The raw script therefore contains no ``${{`` sequence at all,
    so GitHub has nothing to evaluate regardless of quoting.
    """
    return _SHELL_EXPR_LITERAL.join(
        _single_quote_shell(part) for part in text.split(_GH_EXPR)
    )


def _safe_comment(text: str) -> str:
    """Make source-derived text safe inside a ``#`` comment.

    Every embedded newline is re-prefixed so a multi-line stage name or
    source file name cannot introduce a non-comment line (workflow
    structure) into the generated YAML.
    """
    return text.replace("\r\n", "\n").replace("\n", "\n# ")


def _yaml_scalar(value: str) -> str:
    """Emit a string as a safe YAML scalar (plain style only when unambiguous)."""
    if value == "":
        return '""'
    if (
        value in _RESERVED_WORDS
        or _NUMERIC_RE.fullmatch(value)
        or value[0] not in _PLAIN_OK
        or value[-1] == " "
        or not all(ch in _PLAIN_OK for ch in value)
    ):
        return json.dumps(value, ensure_ascii=False)
    return value


def _single_quote_shell(text: str) -> str:
    """Quote text as a single POSIX-shell word preserving every character."""
    return "'" + text.replace("'", "'\\''") + "'"


def generate_workflow(analysis: AnalysisResult, source_name: str = "Jenkinsfile") -> str:
    pipeline = analysis.pipeline
    if pipeline is None:
        # No declarative pipeline: still emit a disabled, documented skeleton.
        pipeline = Pipeline(span=Span(1, 1))

    blockers = [f for f in analysis.findings if f.is_blocker]
    lines: list[str] = []

    lines.append(f"# Generated by pipebridge {__version__} — DO NOT EDIT BY HAND.")
    lines.append(f"# Source: {_safe_comment(source_name)} (sha256: {analysis.source_sha256})")
    lines.append("#")
    if blockers:
        codes = ", ".join(sorted({f.code for f in blockers}))
        lines.append(
            f"# This pipeline had {len(blockers)} migration blocker(s) ({codes})."
        )
        lines.append("# The job below is DISABLED (`if: false`). Read the migration")
        lines.append("# report and resolve every blocker before removing the condition.")
    else:
        lines.append("# No migration blockers detected. Review the assumptions in the")
        lines.append("# migration report before enabling this workflow.")
    lines.append("")

    lines.append("name: Migrated Jenkins pipeline")
    lines.append("on:")
    lines.append("  workflow_dispatch:")
    lines.append("permissions:")
    lines.append("  contents: read")
    lines.append("defaults:")
    lines.append("  run:")
    lines.append("    shell: bash")
    lines.append("")
    lines.append("jobs:")
    lines.append("  migrated-pipeline:")
    if blockers:
        lines.append(
            f"    # Disabled by pipebridge: {len(blockers)} blocker(s) ({', '.join(sorted({f.code for f in blockers}))})."
        )
        lines.append(
            "    # This condition is a literal false: the job never runs until a human removes it."
        )
        lines.append("    if: false")
    lines.append("    runs-on: ubuntu-latest")

    if pipeline.env:
        lines.append("    env:")
        for var in pipeline.env:
            lines.append(f"      {var.name}: {_yaml_scalar(escape_github_expressions(var.value))}")

    steps = _generate_steps(pipeline, blockers)
    if not steps and pipeline.stages:
        # A job requires a steps section; when nothing was translated
        # (pipeline-level blockers), emit a single loud placeholder.
        stage_lines = [
            f'      #   - stage "{_safe_comment(stage.name)}" (line {stage.span.line})'
            for stage in pipeline.stages
        ]
        codes = ", ".join(sorted({f.code for f in blockers})) or "see report"
        steps = [
            "      # No steps were translated: the pipeline contains pipeline-level",
            f"      # blockers ({codes}). Stages found in the source, for manual migration:",
            *stage_lines,
            *_placeholder_step("pipeline", codes),
        ]
    if steps:
        lines.append("    steps:")
        lines.extend(steps)

    lines.append("")
    return "\n".join(lines)


def _placeholder_step(name: str, codes: str) -> list[str]:
    """A placeholder step that fails loudly instead of pretending to succeed."""
    message = (
        f'"{name}" was not migrated: it contains migration blockers ({codes}).'
        " Read migration-report.md and fix deliberately before enabling this"
        " workflow."
    )
    script = f"echo {_expr_safe_shell_quote(message)} >&2\nexit 1"
    return [
        f"      - name: {_yaml_scalar(escape_github_expressions('[NOT MIGRATED] ' + name))}",
        f"        run: {_render_block(script, indent=8)}",
    ]


def _stage_blocker_codes(blockers, stage: Stage, next_stage: Stage | None) -> list[str]:
    """Codes of blockers whose source position falls inside this stage."""
    upper = next_stage.span.line if next_stage is not None else float("inf")
    return sorted({f.code for f in blockers if stage.span.line <= f.line < upper})


def _checkout_step_lines(name: str) -> list[str]:
    """A pinned actions/checkout step (name is source-derived or implicit)."""
    return [
        f"      - name: {_yaml_scalar(escape_github_expressions(name))}",
        f"        uses: {CHECKOUT_ACTION_REPO}@{CHECKOUT_ACTION_SHA}"
        f" # {CHECKOUT_ACTION_VERSION} (pinned to full commit SHA)",
    ]


def _generate_steps(pipeline: Pipeline, blockers) -> list[str]:
    steps: list[str] = []
    if models_implicit_checkout(pipeline):
        # Model Jenkins' default SCM checkout: it happens before the first
        # stage regardless of explicit 'checkout scm' steps, which are kept
        # as-is (a later checkout can change workspace state).
        steps.extend(_checkout_step_lines("Checkout source (implicit)"))
    for index, stage in enumerate(pipeline.stages):
        if pipeline.blocked:
            continue
        if stage.blocked:
            next_stage = pipeline.stages[index + 1] if index + 1 < len(pipeline.stages) else None
            codes = ", ".join(_stage_blocker_codes(blockers, stage, next_stage)) or "see report"
            steps.append(
                f'      # Stage "{_safe_comment(stage.name)}" (line {stage.span.line}) was NOT migrated: it contains'
            )
            steps.append(f"      # unsupported constructs ({codes}). See the migration report.")
            steps.extend(_placeholder_step(stage.name, codes))
            continue
        for idx, step in enumerate(stage.steps, start=1):
            name = stage.name if idx == 1 else f"{stage.name} (step {idx})"
            steps.append(f"      - name: {_yaml_scalar(escape_github_expressions(name))}")
            if stage.env:
                steps.append("        env:")
                for var in stage.env:
                    steps.append(
                        f"          {var.name}: {_yaml_scalar(escape_github_expressions(var.value))}"
                    )
            if step.kind == "checkout":
                # The step's - name: line was already emitted above.
                steps.append(
                    f"        uses: {CHECKOUT_ACTION_REPO}@{CHECKOUT_ACTION_SHA}"
                    f" # {CHECKOUT_ACTION_VERSION} (pinned to full commit SHA)"
                )
                continue
            if step.kind == "echo":
                command = f"printf '%s\\n' {_expr_safe_shell_quote(step.text)}"
            else:
                command = escape_github_expressions(step.text)
            steps.append(f"        run: {_render_block(command, indent=8)}")
    return steps


def _render_block(text: str, indent: int) -> str:
    """Render text as a YAML literal block scalar (explicit indent, strip).

    The explicit indentation indicator (2, relative to the ``run:`` key)
    keeps leading whitespace in the command meaningful regardless of the
    content, and strip chomping avoids inventing trailing newlines. Empty
    text becomes an empty string scalar instead.
    """
    if text == "":
        return '""'
    normalized = text.replace("\r\n", "\n").replace("\r", "\n")
    content_lines = normalized.split("\n")
    while content_lines and content_lines[-1] == "":
        content_lines.pop()
    pad = " " * (indent + 2)
    body = ["|2-"]
    for line in content_lines:
        body.append(pad + line if line else "")
    return "\n".join(body)
